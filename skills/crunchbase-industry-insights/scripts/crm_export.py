#!/usr/bin/env python3
"""Read one or more CRM exports (Salesforce or HubSpot reports, or any CSV/XLSX
with company columns) and collapse them into one row per account.

Usage:
  python crm_export.py --input FILE [--input FILE ...] --out-dir DIR
                       [--owner NAME] [--open-only] [--account NAME_OR_DOMAIN]

Each input may be an accounts/companies export, an opportunities/deals export,
or a contacts export; the kind is detected from the headers. Writes:
  DIR/crm-accounts.csv   one row per account: Account, Domain, CRM ID, Owner,
                         Type, Tier, Industry, Last activity, Open deals,
                         Deal stage, Open amount, Next close date, Won deals,
                         Last won date, Contacts
  DIR/crm-contacts.csv   Account, Domain, Name, Title, Owner, Last activity
                         (email addresses and phone numbers are never written)
  DIR/crm-deals.json     original amount/currency evidence per included deal
  DIR/crm-domains.txt    one account domain per line
and prints a JSON summary. --owner keeps accounts whose owner exactly matches NAME;
--open-only keeps accounts with at least one open deal; --account prints the
matching account (and its contacts) in the summary under "account".
Standard library only; .xlsx needs openpyxl.
"""
from __future__ import annotations

import argparse
import csv
import io
import json
import re
import sys
from datetime import datetime
from pathlib import Path
from urllib.parse import urlsplit
import math

PERSONAL_DOMAINS = {"gmail.com", "googlemail.com", "outlook.com", "hotmail.com", "live.com",
                    "yahoo.com", "icloud.com", "me.com", "aol.com", "proton.me", "protonmail.com"}

# Exact header names first (lowercased), then substring fallbacks.
COLS = {
    "name": ["account name", "company name", "associated company", "account", "company",
             "organization", "organization name", "account: account name"],
    "domain": ["website", "company domain name", "domain", "company domain", "website url",
               "company website", "url", "web site", "account: website"],
    "account_id": ["account id", "account: account id", "company id", "associated company ids",
                   "associated company id", "18 digit account id"],
    "record_id": ["record id", "id"],
    "owner": ["account owner", "company owner", "opportunity owner", "deal owner", "contact owner",
              "owner", "account owner: full name", "opportunity owner: full name"],
    "type": ["type", "account type", "lifecycle stage", "company type"],
    "tier": ["cb_tier__c", "cb tier", "tier", "account tier", "abm tier", "priority"],
    "industry": ["industry"],
    "last_activity": ["last activity", "last activity date", "last activity date (eastern time)",
                      "last engagement date", "recent deal close date"],
    "stage": ["stage", "deal stage", "opportunity stage"],
    "deal_name": ["opportunity name", "deal name"],
    "amount": ["amount", "deal amount", "opportunity amount", "amount (converted)"],
    "currency": ["currency", "currencyisocode", "currency iso code", "currency code", "deal currency code", "opportunity currency"],
    "close_date": ["close date", "expected close date"],
    "first_name": ["first name"],
    "last_name": ["last name"],
    "full_name": ["full name", "contact name", "contact: full name", "name"],
    "title": ["title", "job title", "contact title"],
    "email": ["email", "email address", "contact email"],
}
DROP_HINTS = ("email", "phone", "mobile", "fax", "address", "street", "zip", "postal", "linkedin",
              "twitter", "birth")
FOOTER_RE = re.compile(r"^(grand totals?\b|totals?\s*(\(|:|$)|subtotal\b|copyright\b|"
                       r"confidential information\b|generated by\b|filtered by\b)", re.I)
SF_HINTS = ("account name", "account id", "opportunity name", "account owner", "__c",
            "opportunity owner", "account: ")
HS_HINTS = ("record id", "company domain name", "company owner", "deal stage", "associated company",
            "lifecycle stage", "deal owner", "contact owner")


def die(msg: str) -> None:
    print(json.dumps({"error": msg}))
    sys.exit(1)


def norm_domain(value: str) -> str:
    v = (value or "").strip().lower()
    if not v or " " in v: return ""
    # A supplied contact email is used only for a domain join, never exported.
    if "@" in v and "://" not in v: v = v.rsplit("@", 1)[1]
    parsed = urlsplit(v if "://" in v else "https://" + v)
    if parsed.username or parsed.password: return ""
    host = (parsed.hostname or "").rstrip(".")
    if host.startswith("www."): host = host[4:]
    return host if re.fullmatch(r"[a-z0-9-]+(\.[a-z0-9-]+)+", host) else ""


def csv_cell(value):
    if isinstance(value, str) and value.lstrip().startswith(("=", "+", "-", "@", "\t", "\r")):
        return "'" + value
    return value


def norm_name(value: str) -> str:
    v = (value or "").lower()
    v = re.sub(r"[^\w\s]", " ", v)
    v = re.sub(r"\b(inc|llc|ltd|limited|corp|corporation|co|company|plc|gmbh|sa|ag|bv)\b", " ", v)
    return " ".join(v.split())


def parse_date(value: str) -> str:
    v = (value or "").strip()
    if not v:
        return ""
    if re.fullmatch(r"\d{1,2}/\d{1,2}/\d{2,4}", v):
        first, second = map(int, v.split("/")[:2])
        if first <= 12 and second <= 12 and first != second:
            die("Ambiguous numeric date; use ISO YYYY-MM-DD")
    for cand in (v, v.split()[0].split("T")[0]):
        for fmt in ("%Y-%m-%d", "%m/%d/%Y", "%m/%d/%y", "%d/%m/%Y", "%d.%m.%Y", "%b %d, %Y", "%d %b %Y"):
            try:
                return datetime.strptime(cand, fmt).date().isoformat()
            except ValueError:
                continue
    return ""


def parse_amount(value: str) -> float | None:
    v = re.sub(r"[^\d.\-]", "", value or "")
    try:
        result = float(v) if v not in ("", "-", ".") else None
        if result is not None and not math.isfinite(result): die("Non-finite CRM amount")
        return result
    except ValueError:
        return None


def read_rows(path: Path) -> list[list[str]]:
    if path.suffix.lower() in (".xlsx", ".xlsm"):
        try:
            import openpyxl  # type: ignore
        except ImportError:
            die(f"{path.name}: reading .xlsx needs openpyxl; save the export as CSV instead.")
        wb = openpyxl.load_workbook(path, read_only=True, data_only=True)
        ws = wb.worksheets[0]
        return [["" if c is None else str(c) for c in row] for row in ws.iter_rows(values_only=True)]
    raw = path.read_bytes()
    for enc in ("utf-8-sig", "cp1252", "latin-1"):
        try:
            text = raw.decode(enc)
            break
        except UnicodeDecodeError:
            continue
    sample = text[:8192]
    try:
        dialect = csv.Sniffer().sniff(sample, delimiters=",;\t|")
    except csv.Error:
        dialect = csv.excel
    return [row for row in csv.reader(io.StringIO(text), dialect)]


def find_header(rows: list[list[str]]) -> int:
    known = {n for names in COLS.values() for n in names}
    best, best_hits = 0, -1
    for i, row in enumerate(rows[:15]):
        cells = [c.strip().lower() for c in row if c.strip()]
        if len(cells) < 1:
            continue
        hits = sum(1 for c in cells if c in known)
        if hits > best_hits:
            best, best_hits = i, hits
    return best


def pick(headers: list[str], key: str, taken: set[str]) -> str | None:
    low = {h.strip().lower(): h for h in headers if h and h not in taken}
    for name in COLS[key]:
        if name in low:
            return low[name]
    if key in ("name", "domain", "owner"):
        for name in COLS[key]:
            if len(name) < 5:
                continue
            for lh, h in low.items():
                if name in lh and not any(d in lh for d in DROP_HINTS if d not in name):
                    return h
    return None


def detect_kind(cols: dict) -> str:
    if cols.get("stage") or cols.get("deal_name"):
        return "deals"
    if cols.get("first_name") or cols.get("last_name") or cols.get("email") or (
            cols.get("title") and cols.get("full_name") and cols.get("name")):
        return "contacts"
    return "accounts"


def detect_vendor(headers: list[str]) -> str:
    low = [h.strip().lower() for h in headers]
    sf = sum(1 for h in low for k in SF_HINTS if k in h)
    hs = sum(1 for h in low for k in HS_HINTS if k in h)
    if sf > hs:
        return "salesforce"
    if hs > sf:
        return "hubspot"
    return "unknown"


def load(path: Path) -> dict:
    rows = read_rows(path)
    if not rows:
        die(f"{path.name} is empty.")
    h = find_header(rows)
    headers = [c.strip() for c in rows[h]]
    cols: dict[str, str | None] = {}
    taken: set[str] = set()
    order = ["account_id", "record_id", "domain", "deal_name", "first_name", "last_name", "email",
             "title", "type", "stage", "amount", "currency", "close_date", "owner", "tier", "industry",
             "last_activity", "name", "full_name"]
    for key in order:
        c = pick(headers, key, taken)
        cols[key] = c
        if c:
            taken.add(c)
    kind = detect_kind(cols)
    if kind == "accounts" and not cols.get("name") and cols.get("full_name"):
        cols["name"], cols["full_name"] = cols["full_name"], None
    if not (cols.get("name") or cols.get("domain") or (kind == "contacts" and cols.get("email"))):
        die(f"{path.name}: could not find a company name or website column. Columns: {headers}")
    records, skipped = [], 0
    for row in rows[h + 1:]:
        cells = [c.strip() for c in row] + [""] * (len(headers) - len(row))
        if not any(cells):
            continue
        if FOOTER_RE.match(next(c for c in cells if c)):
            skipped += 1
            continue
        rec = {k: (cells[headers.index(c)] if c else "") for k, c in cols.items()}
        records.append(rec)
    dropped = [x for x in headers if any(d in x.lower() for d in ("email", "phone", "mobile", "fax"))]
    return {"file": path.name, "kind": kind, "vendor": detect_vendor(headers), "columns":
            {k: v for k, v in cols.items() if v}, "records": records, "skipped": skipped,
            "dropped_columns": dropped}


def stage_kind(stage: str) -> str:
    s = re.sub(r"[^a-z]", "", stage.casefold())
    if not s: return "unknown"
    if s in {"closedwon", "won", "closedlost", "lost"}: return "won" if "won" in s else "lost"
    if s in {"prospecting", "qualification", "needsanalysis", "valueproposition", "iddecisionmakers",
             "perceptionanalysis", "proposalpricequote", "negotiationreview", "discovery", "proposal",
             "negotiation", "contractsent", "appointmentscheduled", "qualifiedtobuy", "presentationscheduled",
             "decisionmakerboughtin", "open", "evaluation"}: return "open"
    die("Unknown CRM deal stage; supply a mapping to open, won or lost before normalization")


def is_open(stage: str) -> bool:
    return stage_kind(stage) == "open"


def is_won(stage: str) -> bool:
    return stage_kind(stage) == "won"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--input", action="append", required=True)
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("--owner")
    ap.add_argument("--open-only", action="store_true")
    ap.add_argument("--account")
    a = ap.parse_args()

    files = []
    for p in a.input:
        path = Path(p)
        if not path.exists():
            die(f"File not found: {p}")
        files.append(load(path))

    accounts: dict[str, dict] = {}
    by_name: dict[str, str] = {}
    by_id: dict[str, str] = {}
    merged = 0

    def key_for(name: str, domain: str, acc_id: str) -> str | None:
        if acc_id and acc_id in by_id:
            key = by_id[acc_id]
            if domain and accounts[key]["Domain"] and domain != accounts[key]["Domain"]:
                die("Conflicting domains for one CRM ID; reconcile the input")
            return key
        hits = [k for k, row in accounts.items() if domain and row["Domain"] == domain
                and not (acc_id and row["CRM ID"] and acc_id != row["CRM ID"])]
        return hits[0] if len(hits) == 1 else None

    def upsert(name: str, domain: str, acc_id: str) -> dict | None:
        nonlocal merged
        if not (name or domain):
            return None
        k = key_for(name, domain, acc_id)
        if k:
            merged += 1
            acc = accounts[k]
            acc["Account"] = acc["Account"] or name
            if domain and not acc["Domain"]:
                acc["Domain"] = domain
        else:
            k = f"id:{acc_id}" if acc_id else f"row:{len(accounts)}"
            acc = accounts[k] = {"Account": name, "Domain": domain, "CRM ID": acc_id, "Owner": "",
                                 "Type": "", "Tier": "", "Industry": "", "Last activity": "",
                                 "_deals": [], "_contacts": []}
        if acc_id:
            acc["CRM ID"] = acc["CRM ID"] or acc_id
            by_id[acc_id] = k
        if norm_name(name):
            by_name.setdefault(norm_name(name), k)
        return acc

    def fill(acc: dict, rec: dict, keys=("owner", "type", "tier", "industry")) -> None:
        for src, dst in (("owner", "Owner"), ("type", "Type"), ("tier", "Tier"), ("industry", "Industry")):
            if src in keys and rec.get(src) and not acc[dst]:
                acc[dst] = rec[src]
        la = parse_date(rec.get("last_activity", ""))
        if la and la > acc["Last activity"]:
            acc["Last activity"] = la

    # Accounts first, then deals, then contacts, so IDs and domains are known when joining.
    for f in sorted(files, key=lambda f: ["accounts", "deals", "contacts"].index(f["kind"])):
        for rec in f["records"]:
            domain = norm_domain(rec.get("domain", ""))
            if domain in PERSONAL_DOMAINS:
                domain = ""
            if f["kind"] == "accounts":
                acc_id = rec.get("account_id") or rec.get("record_id") or ""
                acc = upsert(rec.get("name", ""), domain, acc_id)
                if acc:
                    fill(acc, rec)
            elif f["kind"] == "deals":
                acc_id = rec.get("account_id", "")
                acc = upsert(rec.get("name", ""), domain, acc_id)
                if not acc:
                    continue
                fill(acc, rec, keys=("tier", "industry"))
                acc["_deals"].append({"stage": rec.get("stage", ""), "amount": parse_amount(rec.get("amount", "")),
                                      "amount_original": rec.get("amount", ""),
                                      "currency_original": rec.get("currency", ""),
                                      "currency": rec.get("currency", "").strip().upper() if re.fullmatch(r"[A-Za-z]{3}", rec.get("currency", "").strip()) and "converted" not in f["columns"].get("amount", "").lower() else None,
                                      "close": parse_date(rec.get("close_date", "")),
                                      "owner": rec.get("owner", "")})
            else:
                email_dom = norm_domain(rec.get("email", "")) if "@" in rec.get("email", "") else ""
                if email_dom in PERSONAL_DOMAINS:
                    email_dom = ""
                name = rec.get("name", "")
                k = key_for(name, domain or email_dom, rec.get("account_id", ""))
                acc = accounts[k] if k else upsert(name, domain or email_dom, rec.get("account_id", ""))
                if not acc:
                    continue
                person = rec.get("full_name") or " ".join(x for x in (rec.get("first_name"), rec.get("last_name")) if x)
                if person.strip():
                    acc["_contacts"].append({"Name": person.strip(), "Title": rec.get("title", ""),
                                             "Owner": rec.get("owner", ""),
                                             "Last activity": parse_date(rec.get("last_activity", ""))})

    out_rows, contacts, deal_rows = [], [], []
    owners: dict[str, int] = {}
    for acc in accounts.values():
        deals = acc.pop("_deals")
        people = acc.pop("_contacts")
        open_deals = [d for d in deals if is_open(d["stage"])]
        won = [d for d in deals if is_won(d["stage"])]
        if not acc["Owner"]:
            owner_src = open_deals or deals
            acc["Owner"] = next((d["owner"] for d in owner_src if d["owner"]), "")
        nxt = sorted(open_deals, key=lambda d: d["close"] or "9999")
        currencies = {d["currency"] for d in open_deals}
        complete_amount = bool(open_deals) and all(d["amount"] is not None and d["currency"] for d in open_deals) and len(currencies) == 1
        amt = sum(d["amount"] for d in open_deals) if complete_amount else None
        amount_status = ("complete" if complete_amount else "no_open_deals" if not open_deals else
                         "missing_amount" if any(d["amount"] is None for d in open_deals) else
                         "unknown_currency" if None in currencies else "mixed_currencies")
        acc.update({
            "Open deals": len(open_deals) or "",
            "Deal stage": nxt[0]["stage"] if nxt else "",
            "Open amount": (int(amt) if amt == int(amt) else round(amt, 2)) if complete_amount else "",
            "Open amount currency": next(iter(currencies)) if complete_amount else "",
            "Open amount status": amount_status,
            "Next close date": nxt[0]["close"] if nxt else "",
            "Won deals": len(won) or "",
            "Last won date": max((d["close"] for d in won if d["close"]), default=""),
            "Contacts": len(people) or "",
        })
        if a.owner and a.owner.casefold() != acc["Owner"].casefold() and not any(
                a.owner.casefold() == (d["owner"] or "").casefold() for d in deals):
            continue
        if a.open_only and not open_deals:
            continue
        out_rows.append(acc)
        deal_rows.extend({"Account": acc["Account"], "Domain": acc["Domain"], "CRM ID": acc["CRM ID"], **d} for d in deals)
        if acc["Owner"]:
            owners[acc["Owner"]] = owners.get(acc["Owner"], 0) + 1
        for p in people:
            contacts.append({"Account": acc["Account"], "Domain": acc["Domain"], **p})

    out = Path(a.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    acc_cols = ["Account", "Domain", "CRM ID", "Owner", "Type", "Tier", "Industry", "Last activity",
                "Open deals", "Deal stage", "Open amount", "Open amount currency", "Open amount status", "Next close date", "Won deals",
                "Last won date", "Contacts"]
    used = [c for c in acc_cols if c in ("Account", "Domain") or any(r.get(c) not in ("", None) for r in out_rows)]
    with open(out / "crm-accounts.csv", "w", encoding="utf-8-sig", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=used, extrasaction="ignore")
        w.writeheader()
        w.writerows({k: csv_cell(v) for k, v in row.items()} for row in out_rows)
    paths = {"accounts": str(out / "crm-accounts.csv")}
    (out / "crm-deals.json").write_text(json.dumps({"schema_version": "crm-deals/v1", "deals": deal_rows}, indent=2, allow_nan=False), encoding="utf-8")
    paths["deals"] = str(out / "crm-deals.json")
    if contacts:
        with open(out / "crm-contacts.csv", "w", encoding="utf-8-sig", newline="") as fh:
            w = csv.DictWriter(fh, fieldnames=["Account", "Domain", "Name", "Title", "Owner", "Last activity"])
            w.writeheader()
            w.writerows({k: csv_cell(v) for k, v in row.items()} for row in contacts)
        paths["contacts"] = str(out / "crm-contacts.csv")
    domains = sorted({r["Domain"] for r in out_rows if r["Domain"]})
    (out / "crm-domains.txt").write_text("\n".join(domains) + ("\n" if domains else ""), encoding="utf-8")
    paths["domains"] = str(out / "crm-domains.txt")

    vendors = {f["vendor"] for f in files} - {"unknown"}
    summary = {
        "schema_version": 1,
        "currency_policy": "No FX conversion; aggregate only complete same-currency open deals; unknown currency stays unknown",
        "identity_policy": "CRM ID then unique exact domain; no name-only merges",
        "vendor": vendors.pop() if len(vendors) == 1 else ("mixed" if vendors else "unknown"),
        "files": [{"file": f["file"], "kind": f["kind"], "rows": len(f["records"]),
                   "footer_rows_skipped": f["skipped"], "columns": f["columns"],
                   "not_carried": f["dropped_columns"]} for f in files],
        "accounts": len(out_rows),
        "with_domain": sum(1 for r in out_rows if r["Domain"]),
        "name_only": sum(1 for r in out_rows if not r["Domain"]),
        "rows_merged_into_existing_accounts": merged,
        "accounts_with_open_deals": sum(1 for r in out_rows if r.get("Open deals")),
        "contacts": len(contacts),
        "owners": dict(sorted(owners.items(), key=lambda x: -x[1])),
        "filters": {"owner": a.owner, "open_only": a.open_only},
        "paths": paths,
    }
    if a.account:
        q_dom, q_name = norm_domain(a.account), norm_name(a.account)
        hits = [r for r in out_rows if (q_dom and r["Domain"] == q_dom) or
                (not q_dom and q_name and norm_name(r["Account"]) == q_name)]
        hit = hits[0] if len(hits) == 1 else None
        summary["ambiguous_accounts"] = hits if len(hits) > 1 else []
        summary["account"] = ({k: v for k, v in hit.items() if v not in ("", None)} | {
            "contacts": [c for c in contacts if c["Account"] == hit["Account"]]}) if hit else None
    print(json.dumps(summary, indent=1))


if __name__ == "__main__":
    main()
